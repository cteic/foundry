// Pure helpers for the toolchain bench: summarising hyperfine output, comparing
// two runs of one app and rendering the report. The CLIs that shell out are
// toolchain-bench.mjs and toolchain-report.mjs.

/** The steps the bench times, in order. A repo without the script skips the step. */
export const STEPS = ['format:check', 'lint', 'typecheck', 'test', 'build'];

/** Tools whose versions explain a change in time. */
export const TRACKED_TOOLS = [
  'typescript',
  '@typescript/native-preview',
  'eslint',
  'typescript-eslint',
  'oxlint',
  'oxlint-tsgolint',
  'prettier',
  'oxfmt',
  'turbo',
  'next',
  'vitest',
  'jest',
];

export function median(values) {
  if (values.length === 0) throw new Error('median of no values');
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 1 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;
}

/**
 * Summarise one hyperfine result. A step that exited non-zero in any run is
 * marked failed, because the time of a failing command measures nothing useful.
 */
export function summarise(result) {
  const times = result.times ?? result.measurements.map((run) => run.time_wall_clock.value);
  const exitCodes = result.exit_codes ?? result.measurements.map((run) => run.exit_code);
  const failed = exitCodes.some((code) => code !== 0);
  const round = (value) => Math.round(value * 1000) / 1000;
  return {
    median: round(median(times)),
    min: round(Math.min(...times)),
    max: round(Math.max(...times)),
    runs: times.length,
    failed,
  };
}

/** Collect the tracked tool versions from `pnpm ls --recursive --depth 0 --json`. */
export function toolVersions(pnpmList) {
  const found = {};
  for (const project of pnpmList) {
    for (const group of [project.dependencies, project.devDependencies]) {
      for (const [name, info] of Object.entries(group ?? {})) {
        if (!TRACKED_TOOLS.includes(name) || typeof info?.version !== 'string') continue;
        found[name] = [...new Set([...(found[name] ?? []), info.version])].sort();
      }
    }
  }
  return Object.fromEntries(Object.entries(found).sort(([a], [b]) => a.localeCompare(b)));
}

/** Change from `before` to `after` in seconds and per cent. Negative is faster. */
export function change(before, after) {
  const seconds = after - before;
  return { seconds, percent: before === 0 ? 0 : (seconds / before) * 100 };
}

function seconds(value) {
  return `${value.toFixed(1)} s`;
}

function cell(step) {
  if (!step) return '';
  return step.failed ? `${seconds(step.median)} (failed)` : seconds(step.median);
}

function range(step) {
  return step ? `${step.min.toFixed(1)}-${step.max.toFixed(1)} s` : '';
}

/** A change smaller than the spread of either run could be noise, so it is never quoted as a result. */
export function withinNoise(before, after) {
  const spread = Math.max(before.max - before.min, after.max - after.min);
  return Math.abs(after.median - before.median) < spread;
}

function changeCell(before, after) {
  if (!before || !after || before.failed || after.failed) return '';
  const { seconds: diff, percent } = change(before.median, after.median);
  const sign = diff > 0 ? '+' : '';
  const text = `${sign}${diff.toFixed(1)} s (${sign}${percent.toFixed(0)}%)`;
  return withinNoise(before, after) ? `${text}, within noise` : text;
}

/** Runs compare only when both carry the same machine ID. Chip and core count alone match many laptops. */
export function sameMachine(a, b) {
  return typeof a.machine.id === 'string' && a.machine.id === b.machine.id;
}

/** Order runs by capture time, so two runs on one day never swap. */
export function byCaptureTime(a, b) {
  return (a.capturedAt ?? a.date).localeCompare(b.capturedAt ?? b.date);
}

/**
 * Render the report: compare the run labeled baseline (or the first capture
 * if unlabeled) with the latest capture. Runs from different machines are never compared.
 */
export function renderReport(runs) {
  const byApp = new Map();
  for (const run of runs) {
    byApp.set(run.app, [...(byApp.get(run.app) ?? []), run]);
  }

  const lines = [
    '# Toolchain benchmarks',
    '',
    'Generated by `node scripts/toolchain-report.mjs`. Do not edit by hand.',
    '',
    'Each step is the median of the recorded runs, with Turborepo, TypeScript, ESLint and Next.js caches cleared before every run. Each app is cloned at the recorded commit, so a local checkout never affects the numbers.',
    '',
    'Range is the fastest and slowest run. A change smaller than the range of either run is marked within noise: do not quote it as a result.',
    '',
  ];

  for (const [app, appRuns] of [...byApp].sort(([a], [b]) => a.localeCompare(b))) {
    const sorted = [...appRuns].sort(byCaptureTime);
    const baseline = sorted.find((run) => run.label === 'baseline') ?? sorted[0];
    const latest = sorted[sorted.length - 1];
    lines.push(`## ${app}`, '');
    lines.push(
      `${baseline.code.files} TypeScript files, ${baseline.code.lines} lines at the baseline. Machine: ${baseline.machine.chip}, ${baseline.machine.cpus} cores.`,
      ''
    );

    const compare = latest !== baseline && sameMachine(baseline, latest);
    if (latest !== baseline && !compare) {
      lines.push('The latest run is from a different machine, so it is not compared.', '');
    }

    const header = compare
      ? [
          `| Step | ${baseline.label} (${baseline.date}) | Range | ${latest.label} (${latest.date}) | Range | Change |`,
          '| --- | ---: | ---: | ---: | ---: | ---: |',
        ]
      : [`| Step | ${baseline.label} (${baseline.date}) | Range |`, '| --- | ---: | ---: |'];
    lines.push(...header);
    for (const step of STEPS) {
      const before = baseline.steps[step];
      const after = latest.steps[step];
      if (!before && !after) continue;
      lines.push(
        compare
          ? `| \`${step}\` | ${cell(before)} | ${range(before)} | ${cell(after)} | ${range(after)} | ${changeCell(before, after)} |`
          : `| \`${step}\` | ${cell(before)} | ${range(before)} |`
      );
    }
    lines.push('');

    lines.push('| Run | Date | Commit | Tools |', '| --- | --- | --- | --- |');
    for (const run of sorted) {
      const tools = Object.entries(run.tools)
        .map(([name, versions]) => `${name} ${versions.join(', ')}`)
        .join('; ');
      lines.push(`| ${run.label} | ${run.date} | \`${run.commit.slice(0, 7)}\` | ${tools} |`);
    }
    lines.push('');
  }

  return `${lines.join('\n').trimEnd()}\n`;
}

const LABEL = /^[a-z0-9][a-z0-9-]{0,39}$/;

export function parseArgs(argv) {
  const options = { runs: 5, steps: STEPS, ref: 'origin/dev' };
  for (let i = 0; i < argv.length; i += 1) {
    const flag = argv[i];
    const value = argv[i + 1];
    if (value === undefined) throw new Error(`${flag} needs a value`);
    i += 1;
    if (flag === '--repo') options.repo = value;
    else if (flag === '--app') options.app = value;
    else if (flag === '--label') options.label = value;
    else if (flag === '--ref') options.ref = value;
    else if (flag === '--runs') options.runs = Number(value);
    else if (flag === '--steps') options.steps = value.split(',');
    else throw new Error(`unknown flag ${flag}`);
  }
  if (!options.repo) throw new Error('--repo is required');
  if (!options.app || !LABEL.test(options.app))
    throw new Error('--app must be lower-case kebab-case');
  if (!options.label || !LABEL.test(options.label)) {
    throw new Error('--label must be lower-case kebab-case, such as baseline or ts7');
  }
  if (!Number.isInteger(options.runs) || options.runs < 3 || options.runs > 20) {
    throw new Error('--runs must be a whole number from 3 to 20');
  }
  const unknown = options.steps.filter((step) => !STEPS.includes(step));
  if (unknown.length > 0) throw new Error(`unknown steps: ${unknown.join(', ')}`);
  return options;
}
