import lint from '@commitlint/lint';
import load from '@commitlint/load';
import type { UserConfig } from '@commitlint/types';
import { describe, expect, it } from 'vitest';

import { toolNames } from '@cteic/pr-clean';

import config, { createCommitlintConfig, findToolCredit } from './index.js';

async function check(seed: UserConfig, message: string): Promise<string[]> {
  const loaded = await load(seed);
  const parserOpts = loaded.parserPreset?.parserOpts;
  const result = await lint(message, loaded.rules, {
    plugins: loaded.plugins,
    ...(typeof parserOpts === 'object' && parserOpts !== null ? { parserOpts } : {}),
  });
  return result.errors.map((error) => error.name);
}

const subject = 'feat(web): add the landing page';
const [firstTool = ''] = toolNames;
const sessionHost = ['claude', 'ai'].join('.');

describe('@cteic/commitlint-config', () => {
  it('accepts a Conventional Commit with a scope', async () => {
    expect(await check(config, subject)).toEqual([]);
  });

  it('accepts a Conventional Commit without a scope', async () => {
    expect(await check(config, 'chore: bump dependencies')).toEqual([]);
  });

  it('rejects a message without a type', async () => {
    expect(await check(config, 'Added the landing page')).toEqual(
      expect.arrayContaining(['type-empty', 'subject-empty'])
    );
  });

  it('rejects a scope outside the allowed list', async () => {
    const scoped = createCommitlintConfig({ scopes: ['web', 'worker'] });

    expect(await check(scoped, subject)).toEqual([]);
    expect(await check(scoped, 'feat(mobile): add the landing page')).toEqual(['scope-enum']);
  });

  it('rejects tool credit in a scoped config too', async () => {
    const scoped = createCommitlintConfig({ scopes: ['web'] });
    const message = `${subject}\n\nCo-authored-by: ${firstTool} <noreply@anthropic.com>`;

    expect(await check(scoped, message)).toEqual(['no-tool-credit']);
  });

  it.each([
    ['a tool co-author trailer', `Co-authored-by: ${firstTool} <noreply@anthropic.com>`],
    ['a bot co-author trailer', 'Co-Authored-By: coderabbitai[bot] <136622811+bot@example.com>'],
    ['a vendor email co-author', 'Co-authored-by: Helper <helper@openai.com>'],
    ['a tool session trailer', `${firstTool.replaceAll(' ', '-')}-Session: 0123abcd`],
    ['a generated-with line', `Generated with ${firstTool}`],
    ['a generated-by line', 'Generated by a coding tool'],
    ['a session link', `Session: https://${sessionHost}/code/session_0123`],
  ])('rejects %s', async (_name, line) => {
    expect(await check(config, `${subject}\n\n${line}`)).toEqual(['no-tool-credit']);
  });

  it.each(toolNames)('rejects a co-author trailer naming %s', (name) => {
    expect(findToolCredit(`${subject}\n\nCo-authored-by: ${name} <x@example.com>`)).toHaveLength(1);
  });

  it.each([
    ['a human co-author', 'Co-authored-by: Ada Example <ada@example.com>'],
    ['ordinary text about generated code', 'Docs are generated by the build.'],
    ['a git comment line', `# Generated with ${firstTool}`],
  ])('accepts %s', async (_name, line) => {
    expect(await check(config, `${subject}\n\n${line}`)).toEqual([]);
  });

  it('names the lines to delete', async () => {
    const loaded = await load(config);
    const result = await lint(`${subject}\n\nGenerated by a coding tool`, loaded.rules, {
      plugins: loaded.plugins,
    });

    expect(result.errors[0]?.message).toContain('Delete: Generated by a coding tool');
  });
});
