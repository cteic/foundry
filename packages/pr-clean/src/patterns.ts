export type Scope = 'message' | 'diff' | 'body';

export interface CreditPattern {
  id: string;
  description: string;
  regex: RegExp;
  scopes: readonly Scope[];
}

export const toolNames: readonly string[] = [
  'Claude Code',
  'Claude',
  'Codex',
  'Cursor',
  'GitHub Copilot',
  'Copilot',
  'Gemini',
  'ChatGPT',
  'Aider',
  'Devin',
  'Windsurf',
  'Cline',
];

const tools = toolNames.join('|');
const everywhere: readonly Scope[] = ['message', 'diff', 'body'];

export const creditPatterns: readonly CreditPattern[] = [
  {
    id: 'co-authored-by',
    description: 'A co-author trailer',
    regex: /^\s*co-authored-by:\s*\S/i,
    scopes: ['message', 'body'],
  },
  {
    id: 'generated-line',
    description: 'A line that opens with "Generated with" or "Generated by"',
    regex: /^\W*generated (?:with|by)\b/i,
    scopes: ['message'],
  },
  {
    id: 'session-trailer',
    description: 'A trailer that records a coding tool session',
    regex: new RegExp(`^\\s*(?:${tools.replaceAll(' ', '-')})-Session(?:-Id)?:`, 'i'),
    scopes: ['message', 'body'],
  },
  {
    id: 'generated-link',
    description: '"Generated with" or "Generated by" followed by a Markdown link',
    regex: /\bgenerated (?:with|by) \[/i,
    scopes: ['diff', 'body'],
  },
  {
    id: 'generated-tool',
    description: '"Generated with", "by" or "using" followed by a coding tool name',
    regex: new RegExp(`\\b[Gg]enerated (?:with|by|using) (?:the )?(?:${tools})\\b`),
    scopes: ['diff', 'body'],
  },
  {
    id: 'built-with-tool',
    description: '"Built", "written", "created", "made" or "authored" with a coding tool name',
    regex: new RegExp(
      `\\b(?:[Bb]uilt|[Ww]ritten|[Cc]reated|[Mm]ade|[Aa]uthored) (?:with|by|using) (?:the )?(?:${tools})\\b`
    ),
    scopes: everywhere,
  },
  {
    id: 'session-link',
    description: 'A link to a coding tool session',
    regex:
      /\b(?:claude\.ai\/code\/|chatgpt\.com\/codex\/|cursor\.com\/agents|app\.devin\.ai\/sessions\/)/i,
    scopes: everywhere,
  },
];

