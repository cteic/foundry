import { describe, expect, it } from 'vitest';

import type { AddedLine } from './diff.ts';
import {
  checkAttribution,
  checkAuthors,
  checkEmDash,
  checkTrailers,
  dropIgnored,
  isRuleName,
  type Commit,
} from './rules.ts';

const owner = 'Ada Example <ada@example.com>';
const prose = ['*.md', '*.mdx', '*.txt'];

function commit(overrides: Partial<Commit> = {}): Commit {
  return {
    hash: '1111111aaaaaaa',
    authorName: 'Ada Example',
    authorEmail: 'ada@example.com',
    committerName: 'Ada Example',
    committerEmail: 'ada@example.com',
    message: 'feat(api): add export',
    ...overrides,
  };
}

function added(path: string, text: string, line = 1): AddedLine {
  return { path, line, text };
}

describe('checkAuthors', () => {
  it('passes when author and committer are both allowed', () => {
    expect(checkAuthors([commit()], [owner])).toEqual([]);
  });

  it('reports a wrong author with the commit hash', () => {
    const findings = checkAuthors(
      [commit({ hash: 'abc1234', authorName: 'Some Tool', authorEmail: 'tool@example.com' })],
      [owner]
    );

    expect(findings).toEqual([
      {
        rule: 'author',
        check: 'author',
        location: { kind: 'commit', commit: 'abc1234' },
        message: 'The author is not on the allowed list',
        excerpt: 'Some Tool <tool@example.com>',
      },
    ]);
  });

  it('reports a wrong committer even when the author is allowed', () => {
    const findings = checkAuthors(
      [commit({ committerName: 'Some Tool', committerEmail: 'tool@example.com' })],
      [owner]
    );

    expect(findings.map((finding) => finding.check)).toEqual(['committer']);
  });

  it('treats the right name with the wrong email as not allowed', () => {
    expect(checkAuthors([commit({ authorEmail: 'ada@other.example' })], [owner])).toHaveLength(1);
  });

  it('accepts any identity on a list of several', () => {
    const second = commit({ authorName: 'Bo Example', authorEmail: 'bo@example.com' });

    expect(checkAuthors([commit(), second], [owner, 'Bo Example <bo@example.com>'])).toEqual([]);
  });
});

describe('checkTrailers', () => {
  it('passes a plain commit message', () => {
    expect(checkTrailers([commit({ message: 'fix: retry on 429\n\nRefs CTE-1' })])).toEqual([]);
  });

  it('reports a co-author trailer', () => {
    const findings = checkTrailers([
      commit({ message: 'fix: retry\n\nCo-authored-by: Some Tool <tool@example.com>' }),
    ]);

    expect(findings).toMatchObject([
      {
        rule: 'trailers',
        check: 'co-authored-by',
        excerpt: 'Co-authored-by: Some Tool <tool@example.com>',
      },
    ]);
  });

  it('reports a generated-with line, a session trailer and a session link', () => {
    const message = [
      'feat: add export',
      '',
      'Generated with a coding tool',
      'https://claude.ai/code/session_01',
      'Codex-Session: 01',
    ].join('\n');

    expect(checkTrailers([commit({ message })]).map((finding) => finding.check)).toEqual([
      'generated-line',
      'session-link',
      'session-trailer',
    ]);
  });

  it('does not flag a subject that only mentions generated files', () => {
    expect(checkTrailers([commit({ message: 'chore: stop committing generated types' })])).toEqual(
      []
    );
  });
});

describe('checkAttribution', () => {
  it('reports a credit line in an added line with file and line number', () => {
    const findings = checkAttribution(
      [added('README.md', 'Generated with [Some Tool](https://example.com)', 42)],
      undefined
    );

    expect(findings).toMatchObject([
      {
        rule: 'attribution',
        check: 'generated-link',
        location: { kind: 'file', path: 'README.md', line: 42 },
      },
    ]);
  });

  it('reports a credit line in the PR body with its line number', () => {
    const body = '## Summary\n\n- Add export\n\nBuilt with Cursor\n';

    expect(checkAttribution([], body)).toMatchObject([
      { check: 'built-with-tool', location: { kind: 'pr-body', line: 5 } },
    ]);
  });

  it('reports a co-author trailer in the PR body, but not in a file', () => {
    const trailer = 'Co-authored-by: Some Tool <tool@example.com>';

    expect(checkAttribution([], trailer)).toHaveLength(1);
    expect(checkAttribution([added('docs/git.md', trailer)], undefined)).toEqual([]);
  });

  it.each([
    'Docs are generated by the build',
    '// Code generated by protoc-gen-go. DO NOT EDIT.',
    'Built with TypeScript, tested with Vitest',
    'const cursor = rows.created_by;',
  ])('passes ordinary product text: %s', (text) => {
    expect(checkAttribution([added('src/a.ts', text)], text)).toEqual([]);
  });

  it('cuts a long line down to a short excerpt', () => {
    const [finding] = checkAttribution(
      [added('a.md', `Built with Cursor ${'x'.repeat(200)}`)],
      undefined
    );

    expect(finding?.excerpt).toHaveLength(90);
  });
});

describe('checkEmDash', () => {
  const dash = 'one — two';

  it('reports an em dash in an added line of a prose file', () => {
    expect(checkEmDash([], [added('docs/a.md', dash, 7)], undefined, prose)).toMatchObject([
      { rule: 'em-dash', location: { kind: 'file', path: 'docs/a.md', line: 7 } },
    ]);
  });

  it('leaves code files alone by default', () => {
    expect(checkEmDash([], [added('src/a.ts', dash)], undefined, prose)).toEqual([]);
  });

  it('checks code files when the globs say so', () => {
    expect(checkEmDash([], [added('src/a.ts', dash)], undefined, ['*'])).toHaveLength(1);
  });

  it('reports an em dash in a commit message and in the PR body', () => {
    const findings = checkEmDash(
      [commit({ message: `fix: a\n\n${dash}` })],
      [],
      `ok\n${dash}`,
      prose
    );

    expect(findings.map((finding) => finding.location)).toEqual([
      { kind: 'commit', commit: '1111111aaaaaaa' },
      { kind: 'pr-body', line: 2 },
    ]);
  });

  it('passes hyphens and en dashes', () => {
    expect(checkEmDash([], [added('a.md', '2013-2014, Aug 2020 – Nov 2022')], '-', prose)).toEqual(
      []
    );
  });
});

describe('dropIgnored', () => {
  const lines = [
    added('docs/a.md', 'Built with Cursor'),
    added('CHANGELOG.md', 'Built with Cursor'),
    added('docs/b.md', 'Built with Cursor <!-- pr-clean-allow -->'),
  ];

  it('drops lines in ignored paths and lines that hold the allow comment', () => {
    expect(dropIgnored(lines, ['CHANGELOG.md']).map((line) => line.path)).toEqual(['docs/a.md']);
  });
});

describe('isRuleName', () => {
  it('knows the four rules and nothing else', () => {
    expect(['author', 'trailers', 'attribution', 'em-dash'].every(isRuleName)).toBe(true);
    expect(isRuleName('conventional')).toBe(false);
  });
});
