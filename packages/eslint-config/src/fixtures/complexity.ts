export function label(code: number): string {
  if (code === 1) return 'one';
  if (code === 2) return 'two';
  if (code === 3) return 'three';
  if (code === 4) return 'four';
  if (code === 5) return 'five';
  if (code === 6) return 'six';
  if (code === 7) return 'seven';
  if (code === 8) return 'eight';
  if (code === 9) return 'nine';
  if (code === 10) return 'ten';
  return 'many';
}
